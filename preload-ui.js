'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('ui', {
  platform: process.platform,
  send: (text, withScreen) => ipcRenderer.invoke('ai:send', text, !!withScreen),
  stop: () => ipcRenderer.send('ai:stop'),
  history: () => ipcRenderer.invoke('ai:history'),
  clear: () => ipcRenderer.invoke('ai:clear'),
  onDelta: (fn) => ipcRenderer.on('ai:delta', (_e, t) => fn(t)),
  getSettings: () => ipcRenderer.invoke('ai:settings:get'),
  saveSettings: (s) => ipcRenderer.invoke('ai:settings:set', s),
  pickFolder: () => ipcRenderer.invoke('ai:pick-folder'),
  importDsh: () => ipcRenderer.invoke('ai:import-dsh'),
  test: () => ipcRenderer.invoke('ai:test'),
  models: () => ipcRenderer.invoke('ai:models'),
  openSettings: () => ipcRenderer.send('ui:open-settings'),
  openChat: () => ipcRenderer.send('ui:open-chat'),
  close: () => ipcRenderer.send('ui:close'),
  onSettingsChanged: (fn) => ipcRenderer.on('ai:settings-changed', () => fn()),
  onProactive: (fn) => ipcRenderer.on('ai:proactive', (_e, r) => fn(r)),
  openUrl: (u) => ipcRenderer.send('ui:open-url', u),
  stickerTest: () => ipcRenderer.invoke('stickers:test'),
  reminders: () => ipcRenderer.invoke('reminders:list'),
  balance: () => ipcRenderer.invoke('ai:balance'),
  deleteReminder: (id) => ipcRenderer.invoke('reminders:delete', id),
  stickerStatus: () => ipcRenderer.invoke('stickers:status'),
  // voice
  voiceGet: () => ipcRenderer.invoke('voice:get'),
  voiceSet: (s) => ipcRenderer.invoke('voice:set', s),
  voiceTest: (s, text) => ipcRenderer.invoke('voice:test', s, text),
  voiceStop: () => ipcRenderer.send('voice:stop'),
  voiceDownload: (id) => ipcRenderer.invoke('voice:download', id),
  voiceCancelDownload: (id) => ipcRenderer.invoke('voice:cancel-download', id),
  voiceRemoveModel: (id) => ipcRenderer.invoke('voice:remove-model', id),
  transcribe: (samples, rate) => ipcRenderer.invoke('voice:transcribe', samples, rate),
  micAccess: () => ipcRenderer.invoke('voice:mic-access'),
  voiceWarm: (what) => ipcRenderer.send('voice:warm', what),
  onVoiceProgress: (fn) => ipcRenderer.on('voice:progress', (_e, p) => fn(p)),
  onVoiceModels: (fn) => ipcRenderer.on('voice:models', (_e, m) => fn(m)),
  onVoiceChanged: (fn) => ipcRenderer.on('voice:changed', (_e, s) => fn(s)),
  onStartMic: (fn) => ipcRenderer.on('ui:start-mic', () => fn()),
  outfit: () => ipcRenderer.invoke('ui:outfit'),
  setOutfit: (k) => ipcRenderer.send('ui:set-outfit', k),
  onOutfit: (fn) => ipcRenderer.on('ui:outfit', (_e, k) => fn(k)),
});
